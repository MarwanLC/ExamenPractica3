    public void actualizarVista() {
        if (controlador.esVacia()) {
            txtMatricula.setText("Sin coches");
            txtPrecio.setText("");
            txtFecha.setText("");
            
            btnPrimero.setEnabled(false);
            btnAnterior.setEnabled(false);
            btnSiguiente.setEnabled(false);
            btnUltimo.setEnabled(false);
            btnBorrar.setEnabled(false);
        } else {
            Coche actual = controlador.obtenerCocheActual();
            DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            
            txtMatricula.setText(actual.getMatricula());
            txtPrecio.setText(String.valueOf(actual.getPrecio()));
            txtFecha.setText(actual.getFechaMatriculacion().format(formato));

            btnBorrar.setEnabled(true);
            btnPrimero.setEnabled(!controlador.esPrimero());
            btnAnterior.setEnabled(!controlador.esPrimero());
            btnSiguiente.setEnabled(!controlador.esUltimo());
            btnUltimo.setEnabled(!controlador.esUltimo());
        }
    }

