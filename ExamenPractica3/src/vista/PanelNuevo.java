    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String strMatricula = txtMatricula.getText().trim();
        String strPrecio = txtPrecio.getText().trim();
        String strFecha = txtFecha.getText().trim();

        if (!ControlErrores.comprobarMatricula(strMatricula)) {
            lblError.setText("ERROR: Revisa la matrícula. Usa 4 dígitos y 3 letras mayúsculas.");
            return;
        }
        if (!ControlErrores.comprobarPrecio(strPrecio)) {
            lblError.setText("ERROR: El precio debe estar entre 0 y 150000.");
            return;
        }
        if (!ControlErrores.comprobarFecha(strFecha)) {
            lblError.setText("ERROR: Fecha inválida. Usa dd/mm/aaaa (1990-2026).");
            return;
        }

        String matricula = strMatricula;
        float precio = Float.parseFloat(strPrecio);
        LocalDate fecha = ControlErrores.convertirFecha(strFecha);

        controlador.anadirCoche(new Coche(matricula, fecha, precio));

        lblError.setText("");
        txtMatricula.setText("");
        txtPrecio.setText("");
        txtFecha.setText("");
    }//GEN-LAST:event_btnGuardarActionPerformed


